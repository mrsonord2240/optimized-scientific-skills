args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2) stop("Usage: Rscript lsi_run.R input.rds output.rds")
library(Signac)
library(Seurat)
obj <- readRDS(args[1])
if (!"peaks" %in% names(obj@assays) || !"nCount_peaks" %in% colnames(obj[[]])) stop("Need peaks assay and nCount_peaks")
DefaultAssay(obj) <- "peaks"
obj <- RunTFIDF(obj)
obj <- FindTopFeatures(obj, min.cutoff = "q0")
obj <- RunSVD(obj)
embedding <- Embeddings(obj, "lsi")
if (ncol(embedding) < 30) stop("Need at least 30 LSI components for source settings")
corr <- cor(embedding[, 1], obj$nCount_peaks)
if (!is.finite(corr)) stop("Non-finite depth correlation")
dims <- if (abs(corr) > 0.5) 2:30 else 1:30
message(sprintf("LSI1-depth correlation %.3f; retained dimensions %s", corr, paste(dims, collapse = ",")))
obj <- RunUMAP(obj, reduction = "lsi", dims = dims)
obj <- FindNeighbors(obj, reduction = "lsi", dims = dims)
obj <- FindClusters(obj, algorithm = 3, resolution = 0.5)
saveRDS(obj, args[2])
