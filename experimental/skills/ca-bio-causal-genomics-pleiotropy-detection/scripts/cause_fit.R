args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 4) stop("Usage: Rscript cause_fit.R merged.tsv nuisance_snps.txt signal_snps.txt output.rds")
library(cause)
d <- read.delim(args[1], check.names = FALSE)
nuisance <- scan(args[2], what = character(), quiet = TRUE)
signal <- scan(args[3], what = character(), quiet = TRUE)
if (!length(nuisance) || !length(signal) || !all(c(nuisance, signal) %in% d$snp)) stop("SNP lists must be nonempty and present in merged data")
if (length(signal) < 100) warning("Fewer than 100 signal variants; inspect CAUSE stability")
x <- new_cause_data(d)
params <- est_cause_params(x, variants = nuisance)
fit <- cause(X = x, variants = signal, param_ests = params)
saveRDS(list(parameters = params, fit = fit), args[4])
