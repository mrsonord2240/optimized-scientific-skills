args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 4) stop("Usage: Rscript scdblfinder_run.R input.rds capture_column output.rds seed")
library(scDblFinder)
library(SingleCellExperiment)
library(BiocParallel)
sce <- readRDS(args[1])
if (!args[2] %in% colnames(colData(sce)) || anyNA(colData(sce)[[args[2]]])) stop("Missing capture metadata")
seed <- as.integer(args[4])
if (is.na(seed)) stop("Invalid seed")
sce <- scDblFinder(sce, samples = args[2], BPPARAM = SerialParam(RNGseed = seed))
saveRDS(sce, args[3])
