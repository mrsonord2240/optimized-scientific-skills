args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2) stop('usage: Rscript unrooted.R tree.nwk output.pdf')
if (file.exists(args[2])) stop('output already exists')
library(ape)
tr <- read.tree(args[1])
pdf(args[2], width = 7, height = 7)
plot(tr, type = 'unrooted', cex = 0.6, no.margin = TRUE)
add.scale.bar(cex = 0.7, lwd = 1)
dev.off()
