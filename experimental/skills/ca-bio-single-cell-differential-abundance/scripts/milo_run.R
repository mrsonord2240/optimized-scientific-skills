args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2) stop("Usage: Rscript milo_run.R input_sce.rds results.csv")
library(miloR)
library(SingleCellExperiment)
sce <- readRDS(args[1])
meta <- as.data.frame(colData(sce))
if (!all(c("sample", "condition", "cell_type") %in% names(meta)) ||
    anyNA(meta[, c("sample", "condition", "cell_type")])) stop("Missing metadata")
design <- unique(meta[, c("sample", "condition")])
if (length(unique(design$condition)) < 2 || anyDuplicated(design$sample) || any(table(design$condition) < 2) || nrow(design) <= length(unique(design$condition))) stop("Need independent samples and one condition per sample")
rownames(design) <- design$sample
set.seed(42)
milo <- Milo(sce)
milo <- buildGraph(milo, k = 30, d = 30, reduced.dim = "PCA")
milo <- makeNhoods(milo, prop = 0.1, k = 30, d = 30, refined = TRUE, reduced_dims = "PCA")
milo <- countCells(milo, meta.data = meta, samples = "sample")
milo <- calcNhoodDistance(milo, d = 30, reduced.dim = "PCA")
da <- testNhoods(milo, design = ~ condition, design.df = design, reduced.dim = "PCA")
da <- annotateNhoods(milo, da, coldata_col = "cell_type")
write.csv(da, args[2], row.names = FALSE)
