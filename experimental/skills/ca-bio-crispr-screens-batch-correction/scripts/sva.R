args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 3) stop("Usage: Rscript sva.R counts.tsv metadata.tsv design.tsv")
library(sva)
counts_df <- read.delim(args[1], row.names = 1, check.names = FALSE)
metadata <- read.delim(args[2], row.names = 1, check.names = FALSE)
stopifnot(all(colnames(counts_df) %in% rownames(metadata)), "condition" %in% colnames(metadata))
metadata <- metadata[colnames(counts_df), , drop = FALSE]
metadata$condition <- factor(metadata$condition)
mod <- model.matrix(~ condition, data = metadata)
mod0 <- model.matrix(~ 1, data = metadata)
sv_obj <- sva(as.matrix(counts_df), mod, mod0)
design_mat <- cbind(mod, sv_obj$sv)
if (qr(design_mat)$rank < ncol(design_mat)) warning("Design matrix is not full rank")
write.table(design_mat, args[3], sep = "\t", quote = FALSE, col.names = NA)
