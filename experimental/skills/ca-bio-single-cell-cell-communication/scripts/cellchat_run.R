args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 4) stop("Usage: Rscript cellchat_run.R input.rds group_column output.rds interactions.csv")
library(CellChat)
obj <- readRDS(args[1])
if (!args[2] %in% colnames(obj[[]])) stop("Missing group column")
cc <- createCellChat(object = obj, group.by = args[2])
cc@DB <- subsetDB(CellChatDB.human, search = "Secreted Signaling")
cc <- subsetData(cc)
cc <- identifyOverExpressedGenes(cc)
cc <- identifyOverExpressedInteractions(cc)
cc <- computeCommunProb(cc, type = "triMean")
cc <- filterCommunication(cc, min.cells = 10)
cc <- computeCommunProbPathway(cc)
cc <- aggregateNet(cc)
cc <- netAnalysis_computeCentrality(cc, slot.name = "netP")
saveRDS(cc, args[3])
write.csv(subsetCommunication(cc), args[4], row.names = FALSE)
