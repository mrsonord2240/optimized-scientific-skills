#!/usr/bin/env Rscript
# Source ArchR workflow, accepting a CSV with sample and fragments columns.
args <- commandArgs(trailingOnly=TRUE)
if (length(args) != 3) stop('usage: archr_workflow.R samples.csv output_dir /path/to/macs3')
samples <- read.csv(args[1], stringsAsFactors=FALSE)
if (!all(c('sample', 'fragments') %in% names(samples)) || !nrow(samples))
    stop('samples.csv needs non-empty sample and fragments columns')
if (anyDuplicated(samples$sample) || any(!file.exists(samples$fragments)))
    stop('sample names must be unique and all fragment files must exist')
if (file.exists(args[2])) stop('output directory exists; choose a fresh path')
macs <- normalizePath(args[3], mustWork=TRUE)
samples$fragments <- normalizePath(samples$fragments, mustWork=TRUE)
dir.create(args[2], recursive=TRUE)
setwd(args[2])
suppressPackageStartupMessages(library(ArchR))
addArchRGenome('hg38')
arrows <- createArrowFiles(inputFiles=samples$fragments, sampleNames=samples$sample,
                           minTSS=4, minFrags=1000, addTileMat=TRUE, addGeneScoreMat=TRUE)
if (!length(arrows)) stop('no Arrow files produced; inspect ArchR logs and QC')
doubletScores <- addDoubletScores(input=arrows, k=10, knnMethod='UMAP')
proj <- ArchRProject(ArrowFiles=arrows, outputDirectory='ArchR_out')
proj <- filterDoublets(proj)
proj <- addIterativeLSI(proj, useMatrix='TileMatrix', name='IterativeLSI')
proj <- addClusters(proj, reducedDims='IterativeLSI', method='Seurat', resolution=0.5)
proj <- addUMAP(proj, reducedDims='IterativeLSI')
proj <- addGroupCoverages(proj, groupBy='Clusters')
proj <- addReproduciblePeakSet(proj, groupBy='Clusters', pathToMacs2=macs)
proj <- addPeakMatrix(proj)
saveRDS(proj, 'archr_project.rds')
